    headline = str(cta.get("headline") or "Save this for your next review.").strip()
    headline_font, headline_lines = fit_wrapped(draw, headline, CONTENT_W, 3, 82, 60, "serif_bold")
    headline_size = getattr(headline_font, "size", 82)
    y = 300
    for line in headline_lines:
        draw.text((MARGIN, y), line, font=headline_font, fill=WHITE)
