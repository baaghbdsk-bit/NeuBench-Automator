"""Premium LinkedIn carousel and hero renderer.

Produces swipeable PDF carousels and 4:5 hero images from a structured plan
generated by the AI content layer. The design is intentionally editorial:
warm paper, near-black ink, one accent color, large type, no ASCII art, and
no emboldened Unicode glyphs.
"""

from __future__ import annotations

import hashlib
import os
import re
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from PIL import Image, ImageDraw, ImageFont

OUTPUT_DIR = Path("generated_visuals") / "linkedin"
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

W, H = 1080, 1350
MARGIN = 92
CONTENT_W = W - (MARGIN * 2)

INK = (12, 15, 20)
PAPER = (247, 244, 237)
PAPER_SOFT = (236, 231, 221)
ACCENT = (29, 78, 216)
ACCENT_LIGHT = (120, 160, 255)
AMBER = (222, 145, 12)
WHITE = (255, 255, 255)
MUTED_ON_PAPER = (84, 90, 102)
MUTED_ON_DARK = (156, 164, 178)
LINE_ON_PAPER = (208, 202, 190)
LINE_ON_DARK = (48, 55, 68)

if os.name == "nt":
    _FONT_DIR = Path(os.environ.get("WINDIR", r"C:\Windows")) / "Fonts"
else:
    _FONT_DIR = Path("/usr/share/fonts")
_FONT_CACHE: Dict[Tuple[str, int], ImageFont.FreeTypeFont] = {}


